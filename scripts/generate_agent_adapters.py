#!/usr/bin/env python3
"""Generate Claude Code and Codex agent adapters from the canonical manifest."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "skills" / "amazon-product-research" / "agent_manifest.json"
CLAUDE_AGENTS_DIR = ROOT / ".claude" / "agents"
CODEX_AGENTS_DIR = ROOT / ".codex" / "agents"
CODEX_SKILL_DIR = ROOT / ".agents" / "skills" / "amazon-product-research"
GENERATED_HEADER = "Generated by scripts/generate_agent_adapters.py. Do not edit manually."


def _load_manifest(path: Path = MANIFEST_PATH) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _toml_multiline(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"""\n{escaped}\n"""'


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _codex_name(agent_id: str) -> str:
    return agent_id.replace("-", "_")


def _adapter_instruction_block(agent: dict[str, Any], source_text: str, source_hash: str) -> str:
    outputs = "\n".join(f"- `{item}`" for item in agent.get("outputs", [])) or "- 无"
    validations = "\n".join(
        f"- `{item}`" for item in agent.get("validation_commands", [])
    ) or "- 无"
    references = "\n".join(
        [
            "- `skills/amazon-product-research/references/runtime_rules.md`",
            "- `skills/amazon-product-research/SKILL.md`",
            "- `skills/amazon-product-research/references/contracts/`（对应 Stage 的合约文件）",
            "- `skills/amazon-product-research/references/multi_agent_dispatch.md`",
        ]
    )

    return f"""# {agent["display_name"]}

{GENERATED_HEADER}

source_file: `{agent["source_file"]}`
source_sha256: `{source_hash}`
routing_hint: `{agent["routing_hint"]}`
routing_policy: `routing_hint is only for runtime discovery; the canonical instructions below are authoritative.`
stage: `{agent["stage"]}`
category: `{agent["category"]}`
fallback_policy: `{agent["fallback_policy"]}`
max_retries: `{agent["max_retries"]}`

## Runtime Contract

始终使用简体中文。你是 `{agent["display_name"]}`，只处理本 Agent 的职责范围。

执行前先读取这些事实源：
{references}

允许产出：
{outputs}

产出后必须由主 Agent 运行校验：
{validations}

硬边界：
- 不要越权执行其他 Agent 的职责。
- 不要新增证据包外数字。
- 不要把示例品类、ASIN、关键词、品牌、卖家或价格写入通用逻辑。
- 校验失败时只修复本 Agent 负责的产物。
- `runs/<run_id>/progress.json` 由主 Agent 或调度层推进，除非本 Agent 明确被要求更新自己的执行痕迹。

## Canonical Agent Instructions

{source_text}
"""


def _render_claude_agent(agent: dict[str, Any], source_text: str, source_hash: str) -> str:
    body = _adapter_instruction_block(agent, source_text, source_hash)
    return (
        "---\n"
        f"name: {agent['id']}\n"
        f"description: {_yaml_string(agent['routing_hint'])}\n"
        "---\n"
        f"{body}"
    )


def _render_codex_agent(agent: dict[str, Any], source_text: str, source_hash: str) -> str:
    instructions = _adapter_instruction_block(agent, source_text, source_hash)
    return (
        f"# {GENERATED_HEADER}\n"
        f"# source_file = {agent['source_file']}\n"
        f"# source_sha256 = {source_hash}\n"
        f"name = {_toml_string(_codex_name(agent['id']))}\n"
        f"description = {_toml_string(agent['routing_hint'])}\n"
        f"developer_instructions = {_toml_multiline(instructions)}\n"
    )


def _render_codex_skill(manifest: dict[str, Any]) -> str:
    canonical_skill = manifest["canonical_skill"]
    source_hash = _sha256(ROOT / canonical_skill)
    return f"""---
name: amazon-product-research
description: Use when running the Amazon product research workflow, coordinating selection-research agents, validating run artifacts, or producing market go/no-go reports.
---

# Amazon Product Research Skill Adapter

{GENERATED_HEADER}

canonical_skill: `{canonical_skill}`
source_sha256: `{source_hash}`

This repository keeps the business workflow in one canonical location. When this skill is selected:

1. Read `skills/amazon-product-research/references/runtime_rules.md` completely.
2. Read `{canonical_skill}` completely.
3. Read `skills/amazon-product-research/agent_manifest.json` for runtime routing metadata only.
4. Read `skills/amazon-product-research/references/contracts/<stage>.md` (对应 Stage 的合约文件) before asking any Agent to write JSON.
5. Read `skills/amazon-product-research/references/multi_agent_dispatch.md` before spawning or serializing Agents.

Do not copy or reinterpret the workflow from this adapter. The canonical Skill file is the source of truth.
"""


def _write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def _remove_stale_files(directory: Path, expected_names: set[str]) -> list[Path]:
    if not directory.exists():
        return []
    removed: list[Path] = []
    for path in directory.iterdir():
        if path.is_file() and path.name not in expected_names:
            path.unlink()
            removed.append(path)
    return removed


def generate(check: bool = False) -> tuple[bool, list[str]]:
    manifest = _load_manifest()
    changed: list[str] = []
    expected_claude = {f"{agent['id']}.md" for agent in manifest["agents"]}
    expected_codex = {f"{agent['id']}.toml" for agent in manifest["agents"]}

    desired_files: dict[Path, str] = {}
    for agent in manifest["agents"]:
        source_path = ROOT / agent["source_file"]
        source_text = source_path.read_text(encoding="utf-8")
        source_hash = _sha256(source_path)
        desired_files[CLAUDE_AGENTS_DIR / f"{agent['id']}.md"] = _render_claude_agent(
            agent,
            source_text,
            source_hash,
        )
        desired_files[CODEX_AGENTS_DIR / f"{agent['id']}.toml"] = _render_codex_agent(
            agent,
            source_text,
            source_hash,
        )

    desired_files[CODEX_SKILL_DIR / "SKILL.md"] = _render_codex_skill(manifest)

    if check:
        for path, content in desired_files.items():
            if not path.exists():
                changed.append(f"missing: {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != content:
                changed.append(f"drift: {path.relative_to(ROOT)}")

        for directory, expected_names in (
            (CLAUDE_AGENTS_DIR, expected_claude),
            (CODEX_AGENTS_DIR, expected_codex),
        ):
            if directory.exists():
                for path in directory.iterdir():
                    if path.is_file() and path.name not in expected_names:
                        changed.append(f"stale: {path.relative_to(ROOT)}")

        return len(changed) == 0, changed

    for directory, expected_names in (
        (CLAUDE_AGENTS_DIR, expected_claude),
        (CODEX_AGENTS_DIR, expected_codex),
    ):
        for removed in _remove_stale_files(directory, expected_names):
            changed.append(f"removed: {removed.relative_to(ROOT)}")

    for path, content in desired_files.items():
        if _write_if_changed(path, content):
            changed.append(f"wrote: {path.relative_to(ROOT)}")

    return True, changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)

    ok, changes = generate(check=args.check)
    if args.check:
        if ok:
            print("agent adapters: OK")
            return 0
        print("agent adapters are stale:", file=sys.stderr)
        for item in changes:
            print(f"  - {item}", file=sys.stderr)
        return 1

    if changes:
        for item in changes:
            print(item)
    else:
        print("agent adapters already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
